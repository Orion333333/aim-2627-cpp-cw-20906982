"""Check projection privacy, project scope, and incremental export behavior."""

import contextlib
import io
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import export_agent_sessions as exporter


def message(role, text, channel=None):
    return {'type': 'response_item', 'timestamp': '2026-11-07T00:00:00Z',
            'payload': {'type': 'message', 'role': role, 'channel': channel,
                        'content': [{'type': 'output_text', 'text': text}]}}


class ExportTests(unittest.TestCase):
    def test_projection_keeps_only_visible_messages(self):
        records = [message('user', 'Implement Q6'),
                   message('assistant', 'The public tests passed'),
                   message('developer', 'private setup'),
                   message('assistant', 'private thought', 'analysis'),
                   message('user', '<environment_context>private context'),
                   {'type': 'response_item', 'payload': {
                       'type': 'message', 'role': 'assistant', 'content': [{
                           'type': 'reasoning_text', 'text': 'private'}]}},
                   {'type': 'response_item', 'payload': {
                       'type': 'reasoning', 'text': 'private thought'}},
                   {'type': 'response_item', 'payload': {
                       'type': 'custom_tool_call_output', 'output': 'tool'}}]
        raw = '\n'.join(json.dumps(record) for record in records).encode()
        projected, excluded = exporter.visible_messages(raw)
        self.assertEqual([item['role'] for item in projected],
                         ['user', 'assistant'])
        self.assertEqual(projected[0]['content'][0]['text'], 'Implement Q6')
        self.assertNotIn('private', json.dumps(projected))
        self.assertNotIn('tool', json.dumps(projected))
        self.assertIn('reasoning', excluded)

    def test_project_selection_rejects_relative_and_other_cwds(self):
        self.assertTrue(exporter.belongs_here({'cwd': str(exporter.ROOT)}))
        self.assertFalse(exporter.belongs_here({'cwd': '.'}))
        self.assertFalse(exporter.belongs_here({'cwd': 'D:\\other-project'}))
        legacy = next(iter(exporter.LEGACY_SESSION_IDS))
        self.assertTrue(exporter.belongs_here(
            {'id': legacy, 'cwd': 'D:\\cpp'}))

    def test_wrong_repository_cannot_export_the_legacy_chat(self):
        with patch.object(exporter.subprocess, 'check_output',
                          return_value='https://github.com/example/other.git'):
            with self.assertRaises(RuntimeError):
                exporter.check_repository()

    def test_export_is_append_only_when_visible_messages_are_appended(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / 'sessions'
            destination = Path(directory) / 'exports'
            path = source / '2026/11/07/rollout-test.jsonl'
            path.parent.mkdir(parents=True)
            header = {'type': 'session_meta',
                      'payload': {'id': 'test', 'cwd': str(exporter.ROOT)}}
            records = [header, message('user', 'Implement Q6')]
            path.write_text('\n'.join(json.dumps(item) for item in records)
                            + '\n', encoding='utf-8')
            with patch.object(exporter, 'SOURCE', source), \
                    patch.object(exporter, 'DESTINATION', destination), \
                    contextlib.redirect_stdout(io.StringIO()):
                exporter.export_sessions()
                projected = next(destination.rglob('*.jsonl'))
                first = projected.read_bytes()
                with path.open('a', encoding='utf-8') as stream:
                    stream.write(json.dumps(message('assistant', 'Done'))
                                 + '\n')
                exporter.export_sessions()
                self.assertTrue(projected.read_bytes().startswith(first))
                manifest = json.loads((destination / 'manifest.json')
                                      .read_text(encoding='utf-8'))
                self.assertEqual(manifest['sources'][0]['visible_messages'], 2)

    def test_existing_legacy_hook_is_not_overwritten(self):
        with tempfile.TemporaryDirectory() as directory:
            active = Path(directory) / 'pre-commit'
            legacy = Path(directory) / 'pre-commit.legacy'
            active.write_text('# File generated by pre-commit\n')
            legacy.write_text('user-owned hook\n')
            with patch.object(exporter.subprocess, 'check_output',
                              return_value=str(active)):
                with self.assertRaises(RuntimeError):
                    exporter.install_hook()
            self.assertEqual(legacy.read_text(), 'user-owned hook\n')


if __name__ == '__main__':
    unittest.main()
